"""Compile the root SIG list into offline indication/duration lookups."""
import argparse
import hashlib
import json
import re
from pathlib import Path
from xml.etree import ElementTree as ET
from zipfile import ZipFile
from collections import defaultdict

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'Sig Codes (searchable) (1).docx'
TARGET = ROOT / 'src/lib/clinical/sigCodeReference.ts'
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
ns = '{http://schemas.openxmlformats.org/wordprocessingml/2006/main}'
with ZipFile(SOURCE) as archive:
    document = ET.fromstring(archive.read('word/document.xml'))

all_doc_codes = {}
expansion_to_codes = defaultdict(list)
for row in document.findall('.//' + ns + 'tr'):
    cells = [' '.join(t.text or '' for t in cell.findall('.//' + ns + 't')).strip()
             for cell in row.findall(ns + 'tc')]
    if len(cells) >= 2 and max(map(len, cells)) < 1000 and cells[0]:
        code, expansion = cells[:2]
        c = code.strip()
        exp = expansion.strip().upper()
        all_doc_codes[c] = exp
        if c not in expansion_to_codes[exp]:
            expansion_to_codes[exp].append(c)

base_whitelist = {
    'X1', 'SSW', 'SSP', '1V', 'NEB', 'INH', 'OS', 'OD', 'OU',
    'LT', 'RT', 'BIDAC', 'TIDAC', 'QIDAC', 'QDAC', 'AC', 'AP4GM',
    '1RS', '2RS', '1LOZ', '3G', '4G', '5G', 'AL', 'AD', 'AU', 'PV', 'PR', 'SL', 'PO/SL',
    'QDQ2D', 'QOD', 'WMQD', 'WMBID', 'WMTID', 'WM', 'TAW', 'LOR1MG',
    'QD', 'BID', 'TID', 'QID', 'QAM', 'QPM', 'QHS', 'PO', 'GT', 'PEGT', 'JT', 'NG',
    'SQ', 'IM', 'INJ', 'UN', 'DIS', 'ENOS', '1SP', '2SP', 'ACHS', 'NTE4', '3GM', '3GME',
    'PC', 'PCHS', 'PCB', 'PCLU', 'PCS', 'WMHS', 'ACB', 'ACLU', 'ACS', 'A/B', 'A/L', 'A/S', 'P/B', 'P/L', 'P/S',
    'QS', 'QSD', 'QSHIFT', 'TXQS', 'CQOD', 'TXQOD', 'PRN', 'ASN', 'TXPRN',
    'TX1', 'TX2', 'TX3', 'TX4', 'TXQD', 'SAS', 'SC', '12ON',
    'AAA', 'AATX', 'CWS&W', 'CWS&H',
    '1PKT', '1PA', '1CHT', '2CHT', '2T1GM', 'Q2M', 'Q5M', 'QDW/B', 'LOR0.5MG',
    'FOC', '(H', 'LS', 'RMAU', 'AP1/4', 'FOSAMAX', 'DNC',
}

codes = {}
for code, exp in all_doc_codes.items():
    if exp.startswith('FOR ') and not re.match(r'^FOR \d', exp):
        codes[code] = exp
    elif re.fullmatch(r'X\d+(?:D|W|WK|M|H)|Q\d+H|QDQ\d+D|\d+[TCG]', code) or code in base_whitelist:
        codes[code] = exp

for code in list(codes.keys()):
    exp = codes[code]
    for dup in expansion_to_codes[exp]:
        if dup not in codes and (dup in base_whitelist or exp in [codes[c] for c in base_whitelist if c in codes]):
            codes[dup] = exp

# Define canonical priority order for known interchangeable clinical duplicate groups
priority_order = {
    'THREE TIMES A DAY BEFORE MEALS': ['AC', 'TIDAC'],
    'EVERY SHIFT': ['QS', 'QSD', 'QSHIFT'],
    'EVERY OTHER DAY': ['QOD', 'CQOD'],
    'AS NEEDED': ['PRN', 'ASN'],
    'SWISH AND SWALLOW': ['SSW', 'SAS'],
    'SWISH AND SPIT': ['SSP', 'SSSP'],
    'SUBCUTANEOUSLY': ['SQ', 'SC'],
    'AFFECTED AREA:  APPLY': ['AAA', 'AATX'],
    'CLEANSE WITH SOAP AND WATER': ['CWS&W', 'CWS&H'],
    'ONE TIME A DAY BEFORE BREAKFAST': ['A/B', 'ACB'],
    'ONE TIME A DAY BEFORE LUNCH': ['A/L', 'ACLU'],
    'ONE TIME A DAY BEFORE DINNER': ['A/S', 'ACS'],
    'ONE TIME A DAY AFTER BREAKFAST': ['P/B', 'PCB'],
    'ONE TIME A DAY AFTER LUNCH': ['P/L', 'PCLU'],
    'ONE TIME A DAY AFTER DINNER': ['P/S', 'PCS'],
}

standalone_clinical_codes = [
    'PC', 'PCHS', 'ACHS', 'WMHS',
]

equivalent_codes = {}
for exp, pref_list in priority_order.items():
    available = [c for c in pref_list if c in codes]
    for c in available:
        equivalent_codes[c] = available

for c in standalone_clinical_codes:
    if c in codes and c not in equivalent_codes:
        equivalent_codes[c] = [c]

content = ('// Generated by scripts/generate-clinical-code-reference.py; do not edit.\n'
           f'// Source: {SOURCE.name}\n'
           f'// SHA256: {hashlib.sha256(SOURCE.read_bytes()).hexdigest()}\n'
           'export const SIG_CODE_REFERENCE: Readonly<Record<string, string>> = '
           + json.dumps(dict(sorted(codes.items())), indent=2, ensure_ascii=False) + ';\n\n'
           'export const EQUIVALENT_SIG_CODES: Readonly<Record<string, readonly string[]>> = '
           + json.dumps(dict(sorted(equivalent_codes.items())), indent=2, ensure_ascii=False) + ';\n')

if args.check:
    if not TARGET.exists() or TARGET.read_text(encoding='utf-8') != content:
        raise SystemExit('Clinical SIG lookup differs from the root reference. Run the generator.')
    print(f'Clinical SIG lookup matches root reference ({len(codes)} codes)')
else:
    TARGET.write_text(content, encoding='utf-8', newline='\n')
    print(f'Generated {len(codes)} verified clinical codes and equivalent mappings')
